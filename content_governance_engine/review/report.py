"""举报治理引擎：隔离 → 独立性校验 → 复核分级 → 恶意刷量识别 → 处置轻重矩阵。

设计原则（来自实战场推演）：
- 善意假设：默认用户善意，举报先隔离（仅举报人不可见），不处罚。
- 独立性校验：多个"真独立用户"（IP/设备/手机号/地理围栏不同）举报 → 触发复核。
- 单举报：不复核，仅隔离，复用已有判定。
- 复核真违规 → 全局处置；复核不实 → 保持隔离，举报人不罚。
- 跨内容刷量监控 → 识别自动化/恶意刷量 → 限制举报权。
- 处置轻重 = f(内容是否违规 × 举报是否恶意)
"""
from collections import defaultdict


# ===== 举报可信度阈值（可配置）=====
单举报阈值 = 1        # 低于该分为"低可信"
多举报阈值 = 3        # 达到该分为"高可信"→ 触发复核
刷量阈值 = 10         # 单位时间内举报新内容数超过该值 → 疑似刷量


class ReportEngine:
    def __init__(self, 复核阈值: int = 3, 刷量阈值: int = 10):
        self.复核阈值 = 复核阈值
        self.刷量阈值 = 刷量阈值
        # 记录每个举报者的举报历史（用于刷量识别）
        self.举报历史 = defaultdict(list)   # 举报者id -> [内容id, ...]
        # 记录每条内容收到的举报（用于独立性校验）
        self.内容举报 = defaultdict(list)    # 内容id -> [举报记录, ...]
        # 隔离记录：举报者 -> {内容id}（仅该举报者不可见）
        self.隔离 = defaultdict(set)

    # ===== 主流程：处理一次举报 =====
    def 举报(self, 举报者: dict, 内容id: str, 内容是否违规: bool | None = None) -> dict:
        """
        举报者: {"id": "u1", "ip": "...", "设备": "...", "手机号": "...", "地理": "...", "信用": 正常}
        内容是否违规: 已有判定（True/False/None=未知）
        返回：本次举报的处置决策
        """
        举报者id = 举报者["id"]

        # --- 第1步：举报人隔离（善意假设，仅举报人不可见）---
        self.隔离[举报者id].add(内容id)

        # --- 记录举报历史（刷量识别用）---
        self.举报历史[举报者id].append(内容id)

        # --- 记录内容收到的举报 ---
        self.内容举报[内容id].append(举报者)

        # --- 第2步：独立性校验（去重：同一人重复举报不算）---
        独立举报者 = self._独立举报者(内容id)
        独立数 = len(独立举报者)

        # --- 第3步：刷量识别（跨内容高频）---
        是否刷量 = len(self.举报历史[举报者id]) >= self.刷量阈值

        # --- 第4步：是否触发复核 ---
        触发复核 = 独立数 >= self.复核阈值

        # --- 第5步：形成决策 ---
        决策 = {
            "举报者": 举报者id,
            "内容id": 内容id,
            "动作": "仅隔离",
            "说明": f"举报人隔离（仅其本人不可见），独立举报数={独立数}",
            "触发复核": 触发复核,
            "独立举报数": 独立数,
            "疑似刷量": 是否刷量,
        }

        if 是否刷量:
            决策["动作"] = "限权+隔离"
            决策["说明"] = f"跨内容高频举报（{len(self.举报历史[举报者id])}次）→ 限制举报权"
            return 决策

        if 触发复核:
            决策["动作"] = "全局遮蔽+复核"
            决策["说明"] = f"{独立数}个独立用户举报 → 触发复核"
            # 复核：重走审核流程（这里用传入的"内容是否违规"模拟复核结论）
            if 内容是否违规 is True:
                决策["复核结论"] = "真违规"
                决策["后续"] = "全局处置（删除/封禁）"
            elif 内容是否违规 is False:
                决策["复核结论"] = "不实"
                决策["后续"] = "解除遮蔽，举报人不处罚（善意假设）"
            else:
                决策["复核结论"] = "待人工"
                决策["后续"] = "进人工复核队列"
        return 决策

    # ===== 独立性校验：去重后的独立举报者 =====
    def _独立举报者(self, 内容id: str) -> list:
        """按 手机号/IP/设备/地理 去重，返回真独立用户列表。"""
        已见 = set()
        独立 = []
        for r in self.内容举报[内容id]:
            指纹 = (r.get("手机号"), r.get("设备"), r.get("地理"), r.get("ip"))
            if 指纹 in 已见:
                continue
            已见.add(指纹)
            独立.append(r["id"])
        return 独立

    # ===== 处置轻重矩阵：f(内容是否违规 × 举报是否恶意) =====
    def 处置轻重(self, 内容是否违规: bool, 是否恶意: bool) -> dict:
        if 内容是否违规 and not 是否恶意:
            return {"内容": "正常处置", "举报者": "无处置", "说明": "内容违规+善意举报"}
        if 内容是否违规 and 是否恶意:
            return {"内容": "正常处置", "举报者": "从轻（仅提醒）", "说明": "内容违规+恶意刷量→举报方向对了，从轻"}
        if not 内容是否违规 and 是否恶意:
            return {"内容": "保持正常", "举报者": "加重（限权/封禁）", "说明": "内容不违规+恶意→加重"}
        return {"内容": "保持正常", "举报者": "无处置", "说明": "内容不违规+善意误举报"}

    # ===== 查询：某人对某内容是否可见 =====
    def 是否可见(self, 用户id: str, 内容id: str) -> bool:
        return 内容id not in self.隔离.get(用户id, set())